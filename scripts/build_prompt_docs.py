"""Builds docs/prompt_templates.md from the live code, so the prompt text in it is exactly what the app uses.
Calls no AI service: the benchmark prompt is captured by swapping the AI call for a stub."""
import os
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from backend.services import llm  # noqa: E402

captured = {}


def _capture(ctx):
    captured.update(ctx)
    return {"summary": "", "key_drivers": [], "risk_note": ""}


llm._gemini = _capture
os.environ["LLM_PROVIDER"] = "gemini"
llm.explain_benchmark({"kpis": {}, "sector_weights_pct": {}, "stocks": []}, [])
task = captured.get("task", "(not found)")

FENCE = "`" * 3  # the three backticks that open and close a code block in Markdown

TEMPLATE = """# Prompt templates

Generated by `scripts/build_prompt_docs.py` from `backend/services/llm.py`. Do not edit by hand: run the script again after changing a prompt.

Current prompt version: **@@VERSION@@**. The version is stored with every analysis in its audit trail (shown in the compliance panel), and must be changed whenever a prompt changes.

The AI never computes numbers. Code produces every figure first, and the model is asked only to explain them. There are two requests.

## 1. System prompt (used for every AI call)

@@F@@
@@SYSTEM@@
@@F@@

## 2. Portfolio analysis request

The user message is a JSON object built from the analytics output. It contains no names, account numbers or contact details:

| Key | Content |
|---|---|
| `metrics` | Totals, sector weights, the top holding, a concentration index, data age, and a table of holdings (symbol, sector, weight, profit or loss, contribution to return) |
| `alerts` | The rule-based risk alerts, each with a type, severity, value and threshold |
| `alert_count` | How many alerts there are |
| `timeframe` | Recorded, but it does not change the analysis yet |

Required answer, as JSON only:

@@F@@
{"summary": str, "key_drivers": [str], "risk_note": str}
@@F@@

## 3. Benchmark explanation request

The user message is a JSON object with these keys:

| Key | Content |
|---|---|
| `task` | The instruction below |
| `benchmark` | Return, volatility and drawdown against the Nifty 50, sector weights, and each stock's weight and one-year return |
| `recent_headlines` | Up to two recent public headlines per stock, as background only |

Task text:

@@F@@
@@TASK@@
@@F@@

The answer has the same JSON shape as above, and passes the same kind of checks (see `validation_and_policy.md`).

## Provider choice and fallback

1. If `LLM_PROVIDER` is set (`gemini`, `anthropic` or `template`), that provider is used.
2. Otherwise Gemini is used when `GEMINI_API_KEY` exists, then Claude when `ANTHROPIC_API_KEY` exists, and otherwise a template.
3. If a call fails, or its answer fails validation, a template written in code is used. The app never shows an unchecked answer.

## Changing a prompt

1. Edit the text in `backend/services/llm.py`.
2. Increase `PROMPT_VERSION`.
3. Run `pytest`, then `python scripts/build_prompt_docs.py`.
"""

text = (
    TEMPLATE.replace("@@F@@", FENCE)
    .replace("@@VERSION@@", llm.PROMPT_VERSION)
    .replace("@@SYSTEM@@", llm.SYSTEM_PROMPT)
    .replace("@@TASK@@", task)
)
out = ROOT / "docs" / "prompt_templates.md"
out.write_text(text, encoding="utf-8")
print(f"Saved {out}")
print(f"Prompt version: {llm.PROMPT_VERSION}, system prompt {len(llm.SYSTEM_PROMPT)} characters, task text {len(task)} characters")