"""Builds mcp_server/tool_registry.json from the live MCP server, so it always matches the code."""
import asyncio
import json
import sys
from pathlib import Path

from mcp import ClientSession, StdioServerParameters
from mcp.client.stdio import stdio_client

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "mcp_server" / "tool_registry.json"

IMPLEMENTED_IN = {
    "list_portfolios": "mcp_server/tools/portfolio_tools.py",
    "get_portfolio_metrics": "mcp_server/tools/portfolio_tools.py",
    "get_risk_alerts": "mcp_server/tools/portfolio_tools.py",
    "get_stock_price_summary": "mcp_server/tools/market_tools.py",
    "get_recent_news": "mcp_server/tools/news_tools.py",
    "get_benchmark_comparison": "mcp_server/tools/analytics_tools.py",
}


async def main():
    params = StdioServerParameters(
        command=sys.executable, args=["-m", "mcp_server.server"], cwd=str(ROOT)
    )
    async with stdio_client(params) as (read, write):
        async with ClientSession(read, write) as session:
            await session.initialize()
            listed = await session.list_tools()

    registry = {
        "server": "zerodha-portfolio-intelligence",
        "transport": "stdio",
        "note": "Generated by scripts/build_tool_registry.py from the live server. Do not edit by hand.",
        "tools": [
            {
                "name": t.name,
                "description": t.description,
                "input_schema": t.inputSchema,
                "implemented_in": IMPLEMENTED_IN.get(t.name, "unknown"),
            }
            for t in listed.tools
        ],
    }
    OUTPUT.write_text(json.dumps(registry, indent=2), encoding="utf-8")
    print(f"Saved {len(registry['tools'])} tools to {OUTPUT}")
    for tool in registry["tools"]:
        print(" -", tool["name"], "->", tool["implemented_in"])


asyncio.run(main())